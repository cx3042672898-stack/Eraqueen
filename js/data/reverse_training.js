// 设计说明：
//   Layer 1 —— 玩家在接受某个指令时，看到3个行为选项：
//              顺从（配合Star主导）/ 逗弄（撩拨挑逗）/ 主导（反客为主）
//   Layer 2 —— 根据 Layer 1 的选择 + 当前角色状态，进入对应剧情分支
//
// 状态检测键（_rtGetBranchState 返回对象的字段名）：
//   lustRoute  —— 色欲路线激活（tags含'淫乱' 或 lust>=90）
//   loveRoute  —— 恋爱路线激活（tags含'恋慕' 或 affection>=85）
//   yandere    —— 病娇路线激活（tags含'病娇'）
//   highLust   —— 当前欲望 > 80
//   stage3     —— 好感等级 Lv.8+（深度融合期）
//   default    —— 以上均不满足时的兜底
//
// 分支故事的 key 优先级：
//   lustRoute > loveRoute > yandere > stage3 > highLust > default
//
// 经验格式（_rtApplyExpObj 使用）：
//   { slave: {'经验名': 数值}, player: {'经验名': 数值} }
//
// 角色专属扩展：
//   在角色的 DOMContentLoaded 里覆盖以下全局即可接入：
//   window._rtGetChoiceLabels(cmdName, c)  → 自定义选项按钮
//   window._rtGetCharBranchStory(cmd, choiceKey, c, state) → 专属剧情
//   window._rtCharExpMap = { '亲吻': { 顺从: {...}, 逗弄: {...} } }
// ══════════════════════════════════════════════════════════════

// ── 角色状态检测 ──────────────────────────────────────────────
function _rtGetBranchState(c) {
  if (!c) return { stage: 0, highLust: false, lustRoute: false, loveRoute: false, yandere: false, stage3: false };
  var tags = c.tags || [];
  var lv = Math.max(1, Math.min(10, c.affection_level || 1));
  return {
    stage:     lv <= 1 ? 0 : lv <= 4 ? 1 : lv <= 7 ? 2 : 3,
    lustRoute: tags.indexOf('淫乱') >= 0 || (c.lust || 0) >= 90,
    loveRoute: tags.indexOf('恋慕') >= 0 || (c.affection || 0) >= 85,
    yandere:   tags.indexOf('病娇') >= 0,
    highLust:  (c.lust || 0) > 80,
    stage3:    lv >= 8,
  };
}

// ── 从分支故事对象里按状态取对应剧情（返回字符串数组或null）─
// branchPool 结构: { lustRoute:[...], loveRoute:[...], default:[...] }
function _rtPickByState(branchPool, state) {
  if (!branchPool) return null;
  if (state.lustRoute && branchPool.lustRoute && branchPool.lustRoute.length) return branchPool.lustRoute;
  if (state.loveRoute && branchPool.loveRoute && branchPool.loveRoute.length) return branchPool.loveRoute;
  if (state.yandere   && branchPool.yandere   && branchPool.yandere.length)   return branchPool.yandere;
  if (state.stage3    && branchPool.stage3    && branchPool.stage3.length)     return branchPool.stage3;
  if (state.highLust  && branchPool.highLust  && branchPool.highLust.length)   return branchPool.highLust;
  return branchPool.default || null;
}

// ── 经验变化应用 ──────────────────────────────────────────────
// expObj: { slave: {'接吻经验':2, ...}, player: {'调教经验':1, ...} }
function _rtApplyExpObj(expObj, c) {
  if (!expObj || !c) return;
  var slaveExp  = expObj.slave  || {};
  var playerExp = expObj.player || {};
  for (var ek in slaveExp) {
    if (!Object.prototype.hasOwnProperty.call(slaveExp, ek)) continue;
    var rk = (typeof _expCnToKey === 'function') ? _expCnToKey(ek) : ek;
    if (rk && slaveExp[ek]) { c[rk] = (c[rk] || 0) + slaveExp[ek]; }
  }
  for (var pk in playerExp) {
    if (!Object.prototype.hasOwnProperty.call(playerExp, pk)) continue;
    var rpk = (typeof _expCnToKey === 'function') ? _expCnToKey(pk) : pk;
    if (rpk && playerExp[pk] && typeof addPlayerExp === 'function') {
      addPlayerExp(rpk, playerExp[pk]);
    }
  }
}

