// ── 获取道具自用剧情 ─────────────────────────────────────────
// 说明：支持两种写法：
//   ① 直接写 story: [...]              → 正常返回
//   ② 写 dynamicOutcome: () => {...}   → 自动调用，支持性别分支
function getItemSelfStory(itemId) {
  const stories = ITEM_SELF_STORIES[itemId] || ITEM_SELF_STORIES._default;
  const picked  = stories[Math.floor(Math.random() * stories.length)];

  // 如果这条剧情用了 dynamicOutcome（性别分支写法），就调用它
  if (typeof picked.dynamicOutcome === 'function') {
    const resolved = picked.dynamicOutcome();
    // 把 id 带回来，其余字段（story / expChanges 等）从 dynamicOutcome 里取
    return Object.assign({ id: picked.id }, resolved);
  }

  // 普通写法，直接返回
  return picked;
}