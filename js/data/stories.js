// ── 多版本剧情随机抽取器 ──────────────────────────────────────
// 用法：variants 是一个数组，每个元素是一个故事版本的段落数组。
// 若版本数组第一个元素是数字，则视为该版本的权重（不写默认为 1）。
function pickVariant(variants) {
  var total = 0;
  variants.forEach(function(v) { total += (typeof v[0] === 'number' ? v[0] : 1); });
  var r = Math.random() * total;
  for (var i = 0; i < variants.length; i++) {
    var hasW = typeof variants[i][0] === 'number';
    r -= hasW ? variants[i][0] : 1;
    if (r <= 0) return hasW ? variants[i].slice(1) : variants[i];
  }
  var last = variants[variants.length - 1];
  return typeof last[0] === 'number' ? last.slice(1) : last;
}

// ── 经验获得可视化辅助 ────────────────────────────────────────
// 用法：在任意变体数组末尾加一行  _expHtml({ '调教经验': 3, '触手经验': 2 })
// 正数显示绿色 +N，负数显示红色 -N
function _expHtml(gains) {
  var html = Object.keys(gains).map(function(k) {
    var v   = gains[k];
    var sign = v > 0 ? '+' : '';
    var col  = v > 0 ? '#73d18b' : '#e57373';
    return '<b style="color:' + col + ';margin-right:4px">' + k + ' ' + sign + v + '</b>';
  }).join('&nbsp;&nbsp;');
  return '<div data-player-exp="' + encodeURIComponent(JSON.stringify(gains)) + '" style="margin-top:10px;padding:8px 12px;'
       + 'background:rgba(115,209,139,0.08);border-left:3px solid #73d18b;'
       + 'border-radius:4px;font-size:0.85rem;line-height:1.8">'
      + '👑<b>{master}：</b>' + html + '</div>';
}




