// ══════════════════════════════════════════════════════════════
//  核心函数：根据随机选出的两名奴隶及其好感度，返回一段剧情
// ══════════════════════════════════════════════════════════════
// ══════════════════════════════════════════════════════════════════
// ★ 结构化剧情处理器  v2
//
//  支持的格式字段：
//   intro    前置段落（任意层都可用）
//   outro    后置段落（任意层都可用）
//   story    直接内容（无分支时使用）
//   effects  属性变化对象 { affection:2, lust:3, ... }
//
//   scenes   子场景列表（随机选一个满足 when 的场景）
//             [ { when(ctx), intro, story/branches/scenes, outro }, ... ]
//
//   branches 条件分支列表（选第一个满足 when 的分支，无 when = 默认兜底）
//             [ { when(ctx), intro, story/branches, outro }, ... ]
//
//   choices  玩家选择列表（渲染为按钮）
//             [ { text, intro, story/branches, outro, effects }, ... ]
//
//  ctx 字段（由 getObserveSlaveStory 构建）：
//   ctx.A       A的性别字符串
//   ctx.B       B的性别字符串
//   ctx.rel     A×B当前关系分数
//   ctx.has(who, traits)  判断A/B是否有指定性格 ('A'/'B', 字符串数组)
// ══════════════════════════════════════════════════════════════════
function _processStoryDef(def, ctx) {
  var pre = def.intro || [];
  var suf = def.outro || [];

  // ── scenes：从满足条件的子场景里随机选一个 ──────────────────
  if (def.scenes && def.scenes.length > 0) {
    var valid = def.scenes.filter(function(s){ return !s.when || s.when(ctx); });
    if (!valid.length) valid = def.scenes;
    var scene = valid[Math.floor(Math.random() * valid.length)];
    var inner = _processStoryDef(scene, ctx);
    return {
      story:   pre.concat(inner.story).concat(suf),
      choices: inner.choices,
    };
  }

  // ── choices：玩家可选按钮 ────────────────────────────────────
  if (def.choices && def.choices.length > 0) {
    var globalFx = def.effects || {};
    var choices = def.choices.map(function(ch) {
      var body = [].concat(ch.intro || []);
      if (ch.branches && ch.branches.length > 0) {
        var m = null;
        for (var i=0;i<ch.branches.length;i++){
          if (!ch.branches[i].when || ch.branches[i].when(ctx)){m=ch.branches[i];break;}
        }
        if (m) body = body.concat(_processStoryDef(m, ctx).story);
      } else {
        body = body.concat(_processStoryDef({story:ch.story||[],branches:ch._branches}, ctx).story);
      }
      body = body.concat(ch.outro || []).concat(suf);
      var fx = {};
      for (var k in globalFx) fx[k] = globalFx[k];
      for (var k in (ch.effects||{})) fx[k] = (fx[k]||0) + ch.effects[k];
      return { text: ch.text, story: body, effects: fx };
    });
    return { story: pre, choices: choices };
  }

  // ── branches：条件选段（服务端决定，无按钮）──────────────────
  if (def.branches && def.branches.length > 0) {
    var matched = null;
    for (var i=0;i<def.branches.length;i++){
      if (!def.branches[i].when || def.branches[i].when(ctx)){matched=def.branches[i];break;}
    }
    var brInner = matched ? _processStoryDef(matched, ctx) : {story:[]};
    return { story: pre.concat(brInner.story).concat(suf), choices: undefined };
  }

  // ── story：直接内容 ──────────────────────────────────────────
  return { story: pre.concat(def.story || []).concat(suf), choices: undefined };
}

function getObserveSlaveStory() {

  var allChars = (typeof CHARS_DATA !== 'undefined')
    ? CHARS_DATA.filter(function(c){ return loadSave(c.id) && loadSave(c.id).char; })
    : [];

  if (allChars.length < 2) {
    if (allChars.length === 1) {
      var _sv1=loadSave(allChars[0].id);
      var _only=(_sv1&&_sv1.char)?_sv1.char.name:'奴隶';
      return {title:'观察奴隶',story:[
        '今天宅邸里只有'+_only+'一个人。',
        _only+'独自坐在房间里，不知道在想些什么。',
        '……暂时没有可以「互动」的对象，也许是时候去拍卖场看看了。'
      ]};
    }
    return {title:'观察奴隶',story:[
      '宅邸里空荡荡的，目前还没有奴隶可以观察。',
      '也许是时候去拍卖场添些人手了。'
    ]};
  }

  // ── 配对 & 防重复 & 加权随机 ─────────────────────────────────
  var pairs=[];
  for(var _i=0;_i<allChars.length;_i++)
    for(var _j=_i+1;_j<allChars.length;_j++)
      pairs.push({a:allChars[_i],b:allChars[_j],
                  rel:getSlaveRelation(allChars[_i].id,allChars[_j].id)});
  var _lk=localStorage.getItem('era_last_obs_pair')||'';
  var _pl=pairs;
  if(pairs.length>1&&_lk){
    var _ff=pairs.filter(function(p){return[p.a.id,p.b.id].sort().join('|')!==_lk;});
    if(_ff.length>0)_pl=_ff;
  }
  var _tw=0,_ws=_pl.map(function(p){var w=1+p.rel/25;_tw+=w;return w;});
  var _pk=Math.random()*_tw,_ac=0,chosen=_pl[_pl.length-1];
  for(var _wi=0;_wi<_pl.length;_wi++){_ac+=_ws[_wi];if(_pk<=_ac){chosen=_pl[_wi];break;}}
  localStorage.setItem('era_last_obs_pair',[chosen.a.id,chosen.b.id].sort().join('|'));

  var svA=loadSave(chosen.a.id),svB=loadSave(chosen.b.id);
  var charA=(svA&&svA.char)?svA.char:chosen.a;
  var charB=(svB&&svB.char)?svB.char:chosen.b;
  var nameA=charA.name||chosen.a.name, nameB=charB.name||chosen.b.name;
  var relVal=chosen.rel;

  State.storyCharA={id:chosen.a.id,name:nameA,gender:charA.gender||'男'};
  State.storyCharB={id:chosen.b.id,name:nameB,gender:charB.gender||'男'};

  // ── 构建 ctx（含性格辅助函数）────────────────────────────────
  function _toTraits(char) {
    var p = char.personality || char.traits || char.tag || [];
    if (typeof p === 'string') return p.split(/[,，、\s]+/).filter(Boolean);
    return Array.isArray(p) ? p : [String(p)];
  }
  var _tA=_toTraits(charA), _tB=_toTraits(charB);
  var ctx = {
    A:   charA.gender||'男',
    B:   charB.gender||'男',
    rel: relVal,
    // has(who, traits) → A或B是否拥有 traits 中任意一个性格
    has: function(who, traits) {
      var t = who==='A' ? _tA : _tB;
      for(var i=0;i<traits.length;i++) if(t.indexOf(traits[i])!==-1) return true;
      return false;
    },
  };

  var pool;
  if      (relVal>=80){pool=_OBS_T4.concat(_OBS_T3);}
  else if (relVal>=60){pool=_OBS_T3.concat(_OBS_T2);}
  else if (relVal>=30){pool=_OBS_T2.concat(_OBS_T1);}
  else                {pool=_OBS_T1;}

  var raw=pool[Math.floor(Math.random()*pool.length)];
  var taA=charA.gender==='女'?'她':'他', taB=charB.gender==='女'?'她':'他';

  // ── 三种格式识别 ─────────────────────────────────────────────
  var storyObj;
  if (typeof raw==='function') {
    storyObj = raw(charA.gender||'男', charB.gender||'男');
  } else if (raw && !Array.isArray(raw) &&
             (raw.intro!==undefined || raw.scenes!==undefined)) {
    storyObj = _processStoryDef(raw, ctx);
  } else {
    storyObj = { story: Array.isArray(raw)?raw:[raw] };
  }

  function _ph(line){
    return line
      .replace(/\{A\}/g,nameA).replace(/\{B\}/g,nameB)
      .replace(/\{ta_A\}/g,taA).replace(/\{tade_A\}/g,taA+'的')
      .replace(/\{ta_B\}/g,taB).replace(/\{tade_B\}/g,taB+'的');
  }
  var story=(storyObj.story||[]).map(_ph);
  var choices=(storyObj.choices||[]).map(function(ch){
    return{text:_ph(ch.text||''),story:(ch.story||[]).map(_ph),effects:ch.effects||{}};
  });

  var relDelta=relVal>=80?4:relVal>=60?3:relVal>=30?2:1;
  return {
    title:     '观察奴隶：'+nameA+' × '+nameB,
    story:     story,
    choices:   choices.length>0?choices:undefined,
    _charIdA:  chosen.a.id,_charIdB:chosen.b.id,
    _nameA:    nameA,_nameB:nameB,
    _relDelta: relDelta,
  };
}


